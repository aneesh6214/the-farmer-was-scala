using FarmerScala.Editor;
int checks = 0;
void Check(bool condition, string name) { if (!condition) throw new Exception(name); checks++; Console.WriteLine("PASS " + name); }
var palette = new ScalaSyntaxPalette { Class = "T", FunctionDeclaration = "F", FunctionCall = "F", TypeParameter = "T", Builtin = "B", Keyword = "K", String = "S", Number = "N" };
string Paint(CodeWindow window) => ScalaSyntaxHighlighter.Colorize(window.CodeInput.text, palette, semanticSpans: ScalaAnalysis.Spans(window));
bool Blue(CodeWindow window) => Paint(window).Contains("<color=T>ForeignType</color>", StringComparison.Ordinal);
var workspace = new Workspace();
var window = new CodeWindow { workspace = workspace, fileName = "main" };
var other = new CodeWindow { workspace = workspace, fileName = "helper" };
workspace.codeWindows["main"] = window;
workspace.codeWindows["helper"] = other;
MainSim.Inst = new MainSim { workspace = workspace };
window.CodeInput.text = "val value: Option[Int] = None\nval foreign: ForeignType = ???\nval n = 1\n";
other.CodeInput.text = "val other = 1\n";
ScalaAnalysis.Initialize("");
var provider = new DelayedProvider { Ready = true };
ScalaAnalysis.Provider = provider;
Check(Blue(window), "real analysis facade accepts compiler type colors");
provider.Ready = false;
window.CodeInput.text += "val pending =\n";
Check(Blue(window), "unrelated line edits retain compiler-only type colors while analysis is pending");
other.CodeInput.text += "val another =\n";
Check(Blue(window), "editing a different source window retains existing type colors");
window.CodeInput.text = "// 🚜\r\n" + window.CodeInput.text;
Check(Blue(window), "type ranges rebase across inserted emoji and CRLF lines");
window.CodeInput.text = window.CodeInput.text.Replace("ForeignType", "ForeignTypes", StringComparison.Ordinal);
Check(!Paint(window).Contains("<color=T>ForeignTypes</color>", StringComparison.Ordinal), "renamed identifiers lose old compiler classifications immediately");
window.CodeInput.text = "val foreign: ForeignType = ???\n";
provider.Ready = true;
Check(Blue(window), "fresh current analysis replaces the color snapshot");
provider.Ready = false;
window.CodeInput.text = "val ForeignType = 1\nForeignType\n";
Check(!Blue(window), "current local shadowing overrides display-only cached colors");
window.CodeInput.text = "val foreign: ForeignType = ???\n";
provider.Ready = true;
Check(Blue(window), "compiler snapshot can be reseeded after edits");
provider.Kind = "value";
Check(!Blue(window), "current compiler value classification clears obsolete class color");
provider.Kind = "class";
Check(Blue(window), "subsequent authoritative class classification restores type color");
provider.Kind = "value";
window.CodeInput.text = "List(1).map(ForeignType => ForeignType(1))\n";
string variableColors = Paint(window);
Check(!variableColors.Contains("<color=F>ForeignType</color>", StringComparison.Ordinal), "compiler identifies a callable lambda variable as a value");
provider.Ready = false;
other.CodeInput.text += "val pendingValue =\n";
Check(Paint(window) == variableColors, "callable variable colors stay identical while another file is edited");
window.CodeInput.text += "val pendingValue =\n";
Check(!Paint(window).Contains("<color=F>ForeignType</color>", StringComparison.Ordinal), "callable variable colors survive unrelated same-file edits");
window.CodeInput.text = "// 🚜\r\n" + window.CodeInput.text;
Check(!Paint(window).Contains("<color=F>ForeignType</color>", StringComparison.Ordinal), "value classifications rebase across inserted lines");
provider.Ready = true;
provider.Kind = "class";
window.CodeInput.text = "val foreign: ForeignType = ???\n";
Check(Blue(window), "authoritative results replace retained value classifications");
provider.Ready = false;
window.CodeInput.text += "val ForeignType = 1\nForeignType\n";
Check(!Blue(window), "new local shadowing invalidates retained compiler colors before analysis completes");
provider.Ready = true;
window.CodeInput.text = "val foreign: ForeignType = ???\n";
Check(Blue(window), "fresh analysis restores colors after removing the shadow");
provider.Ready = false;
EditorIntegration.ProjectDirectory = "save-b";
Check(!Blue(window), "color snapshots cannot leak into another save");
provider.Ready = true;
Check(Blue(window), "new save uses its own current analysis");
provider.Ready = false;
workspace.codeWindows.Remove("main");
ScalaAnalysis.Spans(other);
workspace.codeWindows["main"] = window;
Check(!Blue(window), "deleting and reopening a module does not resurrect its cached colors");

string types = ScalaSyntaxHighlighter.Colorize("val x: Option[Int] = None", palette);
Check(types.Contains("<color=T>Option</color>", StringComparison.Ordinal) && types.Contains("<color=T>Int</color>", StringComparison.Ordinal), "Option and Int are colored immediately without compiler results");
string shadow = "val Int = 4\nInt\n";
var local = new ScalaCompletionModel(new Dictionary<string, string> { { "a", shadow } });
Check(!ScalaSyntaxHighlighter.Colorize(shadow, palette, semanticSpans: local.Spans("a")).Contains("<color=T>Int</color>", StringComparison.Ordinal), "local values override standard type name fallback");
Check(!ScalaSyntaxHighlighter.Colorize("Mystery", palette).Contains("<color=T>", StringComparison.Ordinal), "arbitrary capitalized names are not guessed to be types");
Check(ScalaSyntaxHighlighter.Colorize("harvest()", palette).Contains("<color=B>harvest</color>", StringComparison.Ordinal), "game builtins retain their separate green category");

SemanticColorSnapshot Member(string text, string name = "farm") => new(text, new[] { new SemanticSpan { Start = text.LastIndexOf(name, StringComparison.Ordinal), Length = name.Length, Kind = "function" } });
Check(Member("bob.farm").Rebase("other.farm").Spans.Count == 0, "changing a receiver invalidates its unchanged member token");
string binding = "def farm() = 1\nfarm\n";
Check(Member(binding).Rebase(binding.Replace("def farm()", "val farm", StringComparison.Ordinal)).Spans.Count == 0, "changing a function declaration to a value invalidates unchanged references");
Check(Member("bob\n .farm").Rebase("other\n .farm").Spans.Count == 0, "multiline receiver edits invalidate stale member colors");
Check(Member("bob.farm").Rebase("bob . farm").Spans.Count == 1, "whitespace between receiver and member preserves colors");
Check(Member("bob.farm").Rebase("// bob.farm").Spans.Count == 0, "commented symbols cannot retain semantic colors");
Check(Member("bob.farm").Rebase("\"bob.farm\"").Spans.Count == 0, "quoted symbols cannot retain semantic colors");
Check(Member("b.`some name`", "`some name`").Rebase("\n b.`some name`").Spans.Single().Length == 11, "backtick names retain exact token ranges");
Check(Member("a ++ b", "++").Rebase("a +++ b").Spans.Count == 0, "edited operator names do not reuse shorter spans");
var input = new SemanticSpan { Start = 0, Length = 3, Kind = "class" };
var copied = new SemanticColorSnapshot("Bob", new[] { input });
input.Start = 90;
Check(copied.Spans.Single().Start == 0, "display snapshot copies caller-owned spans");
Check(new SemanticColorSnapshot("Bob", new[] { new SemanticSpan { Start = -1, Length = 3, Kind = "class" } }).Spans.Count == 0, "invalid provider ranges are discarded");
ScalaAnalysis.Dispose();
string doc = "/** [[ForeignType]] */\nval x = 1";
var docSnapshot = new SemanticColorSnapshot(doc, new[] { new SemanticSpan { Start = 6, Length = 11, Kind = "class" } });
Check(docSnapshot.Rebase(doc + "\n").Spans.Count == 1, "documentation semantic colors persist across unrelated edits");
Check(docSnapshot.Rebase("// ForeignType\n").Spans.Count == 0, "documentation colors do not leak to ordinary comments");
string generic = "def applyTwice[A](value: A)(f: A => A): A = f(f(value))\nval A = 3\nA\n";
var genericModel = new ScalaCompletionModel(new Dictionary<string, string> { { "a", generic } });
var genericSpans = genericModel.Spans("a");
foreach (int at in Enumerable.Range(0, generic.IndexOf("\n", StringComparison.Ordinal)).Where(i => generic[i] == 'A'))
    Check(genericSpans.Any(s => s.Start == at && s.Kind == "typeParameter"), "generic type parameter declaration/reference at " + at);
Check(!genericSpans.Any(s => s.Start == generic.LastIndexOf('A') && s.Kind == "typeParameter"), "type parameter color does not leak outside method scope");
string interpolation = "val value: Option[Int] = Some(3)\nval text = s\"value=$value; ${Some(3).map(x => x + 1)}; $$literal\"";
string interpolatedColor = ScalaSyntaxHighlighter.Colorize(interpolation, palette);
Check(interpolatedColor.Contains("<color=T>Some</color>", StringComparison.Ordinal) && !interpolatedColor.Contains("<color=F>map</color>", StringComparison.Ordinal), "interpolated expression keeps type colors and neutral method calls");
Check(interpolatedColor.Contains("<color=S>; $$literal\"</color>", StringComparison.Ordinal), "escaped dollar stays literal string text");
var interpolationTokens = ScalaLexer.Lex(interpolation);
Check(interpolationTokens.Any(t => t.Text == "value" && t.Start == interpolation.IndexOf("$value", StringComparison.Ordinal) + 1 && t.Identifier), "simple dollar interpolation exposes exact identifier range");
string nested = "s\"outer ${List(1).map(x => s\"inner ${Some(\"}\")} $x\")} done\"";
var nestedTokens = ScalaLexer.Lex(nested);
Check(nestedTokens.Any(t => t.Text == "Some" && t.Identifier) && nestedTokens.Last().Text == " done\"", "nested interpolation and quoted closing brace preserve outer literal");
string triple = "s\"\"\"first\n${Some(1)}\nlast\"\"\"\nval after = 2";
var tripleTokens = ScalaLexer.Lex(triple);
Check(tripleTokens.Single(t => t.Text == "Some").Line == 1 && tripleTokens.Single(t => t.Text == "after").Line == 3, "triple interpolation preserves source lines");
Check(!ScalaLexer.Lex("\"$value ${Some(1)}\"").Any(t => t.Identifier), "plain string dollar content stays literal");
Check(ScalaLexer.Lex("s\"${Some(1)").Any(t => t.Text == "Some"), "unfinished interpolation still highlights code");
var interpolatedSnapshot = new SemanticColorSnapshot(interpolation, new[] { new SemanticSpan { Start = interpolation.IndexOf("Some(3).", StringComparison.Ordinal), Length = 4, Kind = "class" } });
Check(interpolatedSnapshot.Rebase(interpolation + "\n").Spans.Count == 1, "semantic type colors inside interpolation persist while editing");
var unavailableImport = new ScalaCompletionModel(new Dictionary<string, string> { ["draft"] = "import game.Entities.{Tree as FutureTree}\nFut" });
Check(!unavailableImport.Complete("draft", 44).Contains("FutureTree"), "unresolved game import waits for compiler unlock identity instead of leaking through fallback");
string operators = "true && false";
var operatorSpan = new[] { new SemanticSpan { Start = 5, Length = 2, Kind = "function" } };
Check(!ScalaSyntaxHighlighter.Colorize(operators, palette, semanticSpans: operatorSpan).Contains("<color=F>&&</color>", StringComparison.Ordinal), "ordinary symbolic operators retain foreground despite compiler method classification");
ConventionChecks.Run(Check);
NamedArgumentChecks.Run(Check);
DarkPaletteChecks.Run(Check);
Console.WriteLine($"Color stability checks passed: {checks}; production facade/lexer/renderer with delayed compiler adapter.");
