@main def farm(): Unit = {
  assert(get_world_size() == 8)
  val x = get_pos_x()
  val y = get_pos_y()
  for (_ <- 0 until 8) assert(move(East))
  assert(get_pos_x() == x && get_pos_y() == y)
  assert(move(West))
  assert(get_pos_x() == (x + 7) % 8)
  assert(can_move(North))
  harvest()
  if (get_ground_type() != Grounds.Soil) till()
  val before = num_items(Items.Carrot)
  val cost = get_cost(Entities.Carrot).get
  assert(cost.nonEmpty)
  assert(plant(Entities.Carrot))
  assert(get_entity_type().contains(Entities.Carrot))
  assert(get_ground_type(Some(East)) != null)
  assert(get_entity_type(Some(East)) != null)
  val water = get_water()
  assert(use_item(Items.Water))
  assert(get_water() >= water)
  assert(get_time() >= 0 && get_tick_count() > 0)
  val r = random()
  assert(r >= 0 && r < 1)
  do_a_flip()
  change_hat(Hats.Straw_Hat)
  quick_print("FARMING_OK")
}
