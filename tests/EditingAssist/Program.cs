using FarmerScala.Editor;

int checks = 0;
void Check(string name, bool condition)
{
    if (!condition)
        throw new Exception(name);
    checks++;
    Console.WriteLine("PASS " + name);
}
ScalaEditingResult Edit(string marked, char c = '\n', bool backspace = false, ScalaEditingSession? session = null)
{
    int cursor = marked.IndexOf('|');
    string source = marked.Remove(cursor, 1);
    if (!(session ?? new ScalaEditingSession()).TryEdit(source, cursor, cursor, c, backspace, out var edit))
        throw new Exception("Expected handled smart edit: " + marked);
    return edit;
}
string Mark(ScalaEditingResult edit) => edit.Source.Insert(edit.Focus, "|");
bool Code(string marked)
{
    int at = marked.IndexOf('|');
    return ScalaEditingContext.AllowsCompletion(marked.Remove(at, 1), at);
}
